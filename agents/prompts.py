def fmt_planner(total_episodes: int, topic: str) -> tuple[str, str]:
    """格式化 Planner 的 system + user prompt"""
    groups = total_episodes // 10
    system = PLANNER_SYSTEM.format(total_episodes=total_episodes, groups=groups)
    user = PLANNER_USER.format(total_episodes=total_episodes, groups=groups, topic=topic)
    return system, user

def fmt_episode(total_episodes: int, outline: str, use_json: bool = True) -> tuple[str, str]:
    """格式化 Episode Architect 的 system + user prompt。

    Args:
        total_episodes: 总集数
        outline: 大纲文本
        use_json: True=V2 JSON 格式（4维评分），False=旧 markdown 格式
    """
    groups = total_episodes // 10
    if use_json:
        system = EPISODE_SYSTEM_V2.format(total_episodes=total_episodes, groups=groups)
        user = EPISODE_USER_V2.format(total_episodes=total_episodes, groups=groups, outline=outline)
    else:
        system = EPISODE_SYSTEM_LEGACY.format(total_episodes=total_episodes, groups=groups)
        user = EPISODE_USER_LEGACY.format(total_episodes=total_episodes, groups=groups, outline=outline)
    return system, user
